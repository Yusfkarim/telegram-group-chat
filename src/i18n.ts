type Dict = typeof ar;
export type TabKey = keyof typeof AR_TABS;
export type TKey = keyof Dict;

const dir = (lang: Lang) => (lang === "ar" ? "rtl" : "ltr");

export const applyDocumentLang = (lang: Lang) => {
  document.documentElement.lang = lang;
  document.documentElement.dir = dir(lang);
};

export function useT() {
  const lang = useChat((s) => s.settings.lang);
  const dict = (lang === "en" ? en : ar) as Dict;

  const t = useCallback(
    (key: TKey, vars?: Record<string, string | number>) => {
      let out: string = dict[key] ?? key;
      if (vars) for (const [k, v] of Object.entries(vars)) out = out.replace(`{${k}}`, String(v));
      return out;
    },
    [dict]
  );

  const tab = useCallback((which: TabKey) => (lang === "en" ? EN_TABS[which] : AR_TABS[which]), [lang]);
  return { t, tab, lang, dir: dir(lang), isRTL: lang === "ar" };
}

export const presenceText = (
  lang: Lang,
  user: { online: boolean; lastSeen: number; hideLastSeen: boolean } | undefined,
  t: (k: TKey, v?: Record<string, string | number>) => string
) => {
  if (!user) return "";
  if (user.online) return t("online");
  if (user.hideLastSeen) return t("lastSeenHidden");
  return t("lastSeenAt", { t: new Date(user.lastSeen).toLocaleString(lang === "ar" ? "ar" : "en-GB", {
    day: "numeric", month: "short", hour: "2-digit", minute: "2-digit",
  }) });
};